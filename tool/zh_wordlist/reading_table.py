"""Writes lib/core/crypto/zh_reading_table.dart: one common Mandarin
reading per character, for zh-1 input by characters that are not an exact
written form of an entry (an IME homophone slip, handwriting, Zhuyin or
voice input). v0.5.0 plan Task 3.1; spike .devloop/spikes/chinese-words.md
§4 step 3.

Characters: GB2312 (simplified, 6763) and Big5 (traditional, 13053) plus
every character of every zh-1 written form. Readings: pypinyin's first
listed reading (heteronym=False), toneless, ü written v; a character of a
zh-1 entry also gets the reading it has in that entry (长 is zhang first,
chang in 长笛), so a one-character slip of a list word still reaches it.
Few readings on purpose: with every heteronym, about 100k character pairs
named two or more entries (spike, reviewer A); the app also accepts an
input only when exactly one entry matches.

Data: pypinyin 0.53.0 (MIT), whose single-character data is pinyin-data
(MIT), derived from Unihan (Unicode License). Run with the generator's
environment:  tool/zh_wordlist/.venv/bin/python tool/zh_wordlist/reading_table.py
The output is deterministic.
"""

import pathlib
import re
import sys
import unicodedata

from pypinyin import Style, pinyin

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "lib/core/crypto/zh_reading_table.dart"
LIST = ROOT / "lib/core/crypto/zh_wordlist.dart"


def charset(codec: str, ranges) -> set:
    out = set()
    for lead in ranges[0]:
        for trail in ranges[1]:
            try:
                ch = bytes([lead, trail]).decode(codec)
            except UnicodeDecodeError:
                continue
            if len(ch) == 1 and unicodedata.category(ch) == "Lo":
                out.add(ch)
    return out


def list_readings() -> dict:
    """Each character of each zh-1 written form, with the toneless reading
    it has in that entry (from the entry's key)."""
    text = LIST.read_text(encoding="utf-8")
    out = {}
    pattern = (r"ZhWord\('([^']*)', '([^']*)', <String>\[([^\]]*)\], "
               r"'[^']*', '[^']*', '([^']*)'")
    for m in re.finditer(pattern, text):
        forms = [m.group(1), m.group(2)] + re.findall(r"'([^']*)'", m.group(3))
        syllables = m.group(4).split(" ")
        for f in forms:
            if len(f) != len(syllables):
                continue
            for ch, syl in zip(f, syllables):
                out.setdefault(ch, set()).add(syl)
    return out


def main() -> None:
    gb = charset("gb2312", (range(0xB0, 0xF8), range(0xA1, 0xFF)))
    big5 = charset("big5", (range(0xA4, 0xFA), list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF))))
    in_list = list_readings()
    chars = gb | big5 | set(in_list)
    by_syllable = {}
    for ch in sorted(chars):
        r = pinyin(ch, style=Style.NORMAL, heteronym=False, v_to_u=True)[0][0]
        r = r.replace("ü", "v")
        readings = set(in_list.get(ch, ()))
        if re.fullmatch(r"[a-z]+", r) and r != ch:
            readings.add(r)
        for syl in sorted(readings):
            by_syllable.setdefault(syl, []).append(ch)
    # CJK compatibility ideographs whose canonical form (NFC) is one of the
    # characters above: an input method or a paste can carry them.
    compat = {}
    for cp in list(range(0xF900, 0xFB00)) + list(range(0x2F800, 0x2FA20)):
        ch = chr(cp)
        unified = unicodedata.normalize("NFC", ch)
        if unified != ch and unified in chars:
            compat[cp] = ord(unified)
    lines = [f"{syl}\\t{''.join(cs)}" for syl, cs in sorted(by_syllable.items())]
    n = len({ch for cs in by_syllable.values() for ch in cs})
    body = "\\n".join(lines)
    OUT.write_text(
        "// Generated by tool/zh_wordlist/reading_table.py; do not edit.\n"
        "//\n"
        "// Mandarin readings (toneless, u-umlaut written v) of\n"
        f"// {n} characters (GB2312, Big5 and every zh-1 written form): pypinyin's\n"
        "// first reading, plus the reading a character has in a zh-1 entry. One\n"
        "// line per syllable: the syllable, a tab, then its characters (a\n"
        "// character with two readings is on two lines). Used only to read zh-1\n"
        "// input by characters that are not an exact form.\n"
        "//\n"
        "// Data: pypinyin 0.53.0 (MIT), from pinyin-data (MIT), derived from\n"
        "// Unihan (Unicode License).\n"
        "// ignore_for_file: lines_longer_than_80_chars\n"
        "\n"
        f"const String zhReadingTable = '{body}';\n"
        "\n"
        "/// CJK compatibility ideographs and the unified character each stands for.\n"
        "const Map<int, int> zhCompatibilityIdeographs = <int, int>{\n"
        + "".join(f"  0x{k:X}: 0x{v:X},\n" for k, v in sorted(compat.items()))
        + "};\n",
        encoding="utf-8",
    )
    print(f"{n} characters, {len(by_syllable)} syllables, {OUT.stat().st_size} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
