"""Freeze zh-1 (plan Task 2.5; spike chinese-words.md "Checked-in list").

  uv run freeze.py [--check]

Takes the 2048 highest-ranked words of out/candidates.tsv that every
reviewer in review.REVIEWERS kept, orders them by canonical key, and writes
lib/core/crypto/zh_wordlist.dart plus its SHA-256 (printed, and checked by
test/crypto/zh_wordlist_test.dart). --check writes nothing and fails if the
file on disk differs from what would be written.

Each index holds, in serialization order:
  simplified, traditional (OpenCC s2tw), extra accepted written forms (other
  OpenCC forms: s2t, s2hk), tone-marked Mainland pinyin, Taiwan Zhuyin,
  canonical toneless key (ASCII, ü written v, syllables space-separated),
  accepted Latin readings.
Serialization for the checksum: UTF-8, NFC, one line per index in index
order, fields separated by U+0009, multi-valued fields joined with U+002C,
LF line ends. The accepted readings are the standard reading only: no
alternate reading was reviewed, and input-side tolerance (mergers, missing
tones) belongs to the matcher, not the list.

Once the file is committed the list never changes; any change is zh-2.
"""

import argparse
import hashlib
import sys
import unicodedata
from pathlib import Path

import sound
from review import REVIEWERS, decided, read_tsv

HERE = Path(__file__).resolve().parent
DART = HERE.parent.parent / "lib" / "core" / "crypto" / "zh_wordlist.dart"

HEADER = """\
// zh-1: Signet's Chinese word list (2048 Mandarin words of two or three
// characters; three-character words are nouns). FROZEN: never edit this file;
// any change is a new list id (zh-2). Generated by tool/zh_wordlist/freeze.py;
// test/crypto/zh_wordlist_test.dart checks its SHA-256 and integrity.
//
// Each entry: simplified form; Taiwan traditional form (OpenCC s2tw); other
// accepted written forms (OpenCC s2t, s2hk); Mainland pinyin; Taiwan Zhuyin;
// canonical toneless key (ASCII, u-umlaut written v); accepted Latin readings.
// Entries are ordered by key.
//
// Sources (see tool/zh_wordlist/SOURCES.md): headwords from the HSK 3.0
// syllabus (GF0025-2021) and nouns attested in SUBTLEX-CH; pinyin from
// pypinyin (MIT); traditional forms from OpenCC (Apache-2.0); Zhuyin from
// libchewing data (LGPL-2.1-or-later) or McBopomofo (MIT). Readings were
// checked against the MOE dictionary, which is not a source of anything here.
// The selection, order and curation are Signet's work under AGPL-3.0.
// ignore_for_file: lines_longer_than_80_chars

class ZhWord {
  const ZhWord(this.simplified, this.traditional, this.otherForms, this.pinyin,
      this.zhuyin, this.key, this.readings);

  final String simplified;
  final String traditional;
  final List<String> otherForms;
  final String pinyin;
  final String zhuyin;
  final String key;
  final List<String> readings;
}

const List<ZhWord> zhWordlist = <ZhWord>[
"""


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s)


def key_of(pinyin: str) -> str:
    return " ".join(s.replace("ü", "v") for s in sound.detone(pinyin))


def entries() -> list:
    d = decided()
    rows = [r for r in read_tsv(HERE / "out" / "candidates.tsv")
            if all(d.get((x, r["simplified"]), ("",))[0] == "keep" for x in REVIEWERS)]
    rows.sort(key=lambda r: int(r["rank"]))
    if len(rows) < 2048:
        sys.exit(f"only {len(rows)} words kept by every reviewer")
    out = []
    for r in rows[:2048]:
        key = key_of(r["pinyin"])
        out.append({
            "simplified": nfc(r["simplified"]), "traditional": nfc(r["tw"]),
            "other": [nfc(f) for f in r["other_forms"].split()], "pinyin": nfc(r["pinyin"]),
            "zhuyin": nfc(r["zhuyin"]), "key": key, "readings": [key],
        })
    out.sort(key=lambda e: (e["key"], e["simplified"]))
    keys = [e["key"] for e in out]
    if len(set(keys)) != len(keys):
        sys.exit("two entries share a canonical key")
    return out


def serialize(es: list) -> str:
    return "".join("\t".join([e["simplified"], e["traditional"], ",".join(e["other"]), e["pinyin"],
                              e["zhuyin"], e["key"], ",".join(e["readings"])]) + "\n" for e in es)


def dart(es: list) -> str:
    def q(s):
        assert "'" not in s and "\\" not in s and "$" not in s
        return f"'{s}'"

    def lst(xs):
        return "<String>[" + ", ".join(q(x) for x in xs) + "]"

    body = "".join(f"  ZhWord({q(e['simplified'])}, {q(e['traditional'])}, {lst(e['other'])}, {q(e['pinyin'])}, "
                   f"{q(e['zhuyin'])}, {q(e['key'])}, {lst(e['readings'])}),\n" for e in es)
    return HEADER + body + "];\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    es = entries()
    digest = hashlib.sha256(serialize(es).encode("utf-8")).hexdigest()
    text = dart(es)
    if args.check:
        same = DART.exists() and DART.read_text(encoding="utf-8") == text
        print(f"sha256 {digest}; {DART} {'matches' if same else 'DIFFERS'}")
        return 0 if same else 1
    DART.write_text(text, encoding="utf-8")
    print(f"wrote {len(es)} entries to {DART}\nsha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
